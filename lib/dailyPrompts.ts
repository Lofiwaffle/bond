function hashString(input: string): number {
  let h = 0
  for (let i = 0; i < input.length; i++) {
    h = (h * 31 + input.charCodeAt(i)) >>> 0
  }
  return h
}

/** Same prompt for both partners on a given local calendar day. */
export function promptForDate(coupleId: string, isoDate: string): DailyPrompt {
  const [year, month, day] = isoDate.split('-').map(Number)
  const dayNumber = Math.floor(Date.UTC(year, month - 1, day) / 86400000)
  const offset = hashString(coupleId) % DAILY_PROMPTS.length
  const index = (offset + dayNumber) % DAILY_PROMPTS.length
  return DAILY_PROMPTS[index] ?? DAILY_PROMPTS[0]
}

export function promptById(id: string | null | undefined): DailyPrompt | undefined {
  if (!id) return undefined
  return DAILY_PROMPTS.find((prompt) => prompt.id === id)
}
